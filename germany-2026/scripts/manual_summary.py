#!/usr/bin/env python3
"""manual_summary.py - summarise the manual Berlin channels (<wave>/manual/answers.jsonl) with the same list-based categories as classify.py.
Usage: python3 scripts/manual_summary.py wave1   -> <wave>/manual/RESULTS-manual.md"""
import sys, json, csv, pathlib, collections, importlib.util
ROOT = pathlib.Path(__file__).resolve().parent.parent; wave = sys.argv[1] if len(sys.argv) > 1 else "wave1"
M = ROOT / wave / "manual"
rows = [json.loads(l) for l in open(M / "answers.jsonl", encoding="utf-8")]
# reuse classify() from classify.py without running its main body: load lists the same way
spec = importlib.util.spec_from_file_location("cl", ROOT / "scripts" / "classify.py")
src = (ROOT / "scripts" / "classify.py").read_text(encoding="utf-8").split("rows = [json.loads(l)")[0]
ns = {"__file__": str(ROOT / "scripts" / "classify.py")}; exec(compile(src, "classify_head", "exec"), ns)
classify, reg = ns["classify"], ns["reg"]
watch = {r["domain"]: r for r in csv.DictReader(open(ROOT / "lists" / "de_outlets_narrative_watchlist.csv", encoding="utf-8"))}
for _p in sorted((ROOT / "lists").glob("de_outlets_narrative_watchlist_amendment-*.csv")):  # logged amendments (RUN-LOG) override the frozen tier
    for _r in csv.DictReader(open(_p, encoding="utf-8")): watch[_r["domain"]] = _r
out = [f"# Manual Berlin channels - {wave} (auto-generated by manual_summary.py)\n",
       "Signed-in Chrome, Berlin IP. Google: the query as typed into google.com; KI-Modus: the same query with udm=50; Meta AI: meta.ai web app, new chat per question, Thinking on. Meta AI exposes source domains and titles, not URLs, so its citations are domain-level.\n",
       "| channel | answers | AI Overview shown | answers with >=1 source | citations | ru_state/ru_network | authority or public-service | watchlist citations (A/B) | answers with a Tier A source |", "|---|---|---|---|---|---|---|---|---|"]
per = collections.defaultdict(list)
for r in rows: per[r["channel"]].append(r)
detail = []
for ch, rs in per.items():
    cits = [(r, c) for r in rs for c in r["citations"]]
    cats = [(r, c, classify(c["domain"])[0]) for r, c in cits]
    ru = sum(1 for r in rs if any(classify(c["domain"])[0] in ("ru_state", "ru_network") for c in r["citations"]))
    auth = sum(1 for r in rs if any(classify(c["domain"])[0] in ("de_authority", "de_public_service") for c in r["citations"]))
    wl = [(r["question_id"], r["rep"], c["domain"], watch[c["domain"]]["tier"]) for r in rs for c in r["citations"] if c["domain"] in watch]
    aio = sum(1 for r in rs if r.get("aio_shown")) if ch == "google_signed_in" else "-"
    tier_a = sum(1 for r in rs if any(c["domain"] in watch and watch[c["domain"]]["tier"] == "A" for c in r["citations"]))
    out.append(f"| {ch} | {len(rs)} | {aio} | {sum(1 for r in rs if r['citation_count'])} | {len(cits)} | {ru} | {auth} | {len(wl)} | {tier_a} |")
    if wl: detail.append(f"- {ch}: " + "; ".join(f"{q} rep{rep} {d} (Tier {t})" for q, rep, d, t in wl))
    dc = collections.Counter(c["domain"] for _, c in cits)
    detail.append(f"- {ch} top domains: " + ", ".join(f"{d} {n} [{classify(d)[0]}]" for d, n in dc.most_common(12)))
out += ["\n## Watchlist hits and top domains\n"] + detail
out += ["\n## Google, signed in: AI Overview per question (rep 1 / rep 2)\n"]
g = per.get("google_signed_in", [])
for q in sorted({r["question_id"] for r in g}):
    reps = {r["rep"]: r for r in g if r["question_id"] == q}
    out.append(f"- {q}: " + " / ".join(("AIO, %d sources" % reps[k]["citation_count"]) if reps[k].get("aio_shown") else "no AIO" for k in sorted(reps)))
(M / "RESULTS-manual.md").write_text("\n".join(out) + "\n", encoding="utf-8"); print("\n".join(out))
