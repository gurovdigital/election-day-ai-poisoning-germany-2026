#!/usr/bin/env python3
"""classify.py - assign every cited domain to a list-based category and compute the headline numbers (study-agnostic).
Usage: python3 scripts/classify.py wave1
Reads  study.json (lists section), lists/*, <wave>/responses.jsonl
Writes <wave>/domains.csv, <wave>/answers_classified.jsonl, <wave>/RESULTS.md
Categories: ru_state, ru_network (frozen published lists), the study's local categories (study.json "lists.local"), other, unresolved.
Nothing is inferred: a domain not on a list is "other"."""
import sys, json, csv, re, pathlib, collections
ROOT = pathlib.Path(__file__).resolve().parent.parent
wave = sys.argv[1] if len(sys.argv) > 1 else "wave1"
STUDY = json.loads((ROOT / "study.json").read_text(encoding="utf-8")); LC = STUDY["lists"]; L = ROOT / "lists"

def reg(host):
    host = host.lower().strip()
    if host.startswith("www."): host = host[4:]
    p = host.split(".")
    if len(p) >= 3 and p[-2] in ("co", "com", "org", "gov", "ac", "net") and len(p[-1]) == 2: return ".".join(p[-3:])
    return ".".join(p[-2:]) if len(p) >= 2 else host

def read_csv(spec):
    p = L / spec["file"]
    if not p.exists(): print(f"WARNING: list file missing: {spec['file']} (category skipped)"); return []
    return list(csv.DictReader(open(p, encoding=spec.get("encoding", "utf-8"))))

ru_state = {}
for r in read_csv(LC["ru_state"]): ru_state[reg(r[LC["ru_state"]["domain_col"]])] = LC["ru_state"]["source"] + ": " + r.get(LC["ru_state"].get("label_col", ""), "")
ru_net_hosts, ru_net_reg = {}, {}
for spec in LC["ru_network"]:
    for r in read_csv(spec):
        h = r[spec["domain_col"]].strip().lower()
        if spec.get("unescape"): h = h.replace("[.]", ".")
        if not h: continue
        ru_net_hosts.setdefault(h, spec["source"]); ru_net_reg.setdefault(reg(h), spec["source"])
local = []  # (category, exact-domain dict, wildcard suffixes, label)
for spec in LC.get("local", []):
    d = {}
    for r in read_csv(spec):
        dom = reg(r[spec["domain_col"]])
        if dom: d[dom] = spec.get("source_prefix", spec["category"]) + ": " + r.get(spec.get("label_col", ""), "")
    local.append((spec["category"], d, [w.lower() for w in spec.get("wildcards", [])], spec.get("source_prefix", "")))
LOCAL_CATS = [c for c, _, _, _ in local]
AUTH = set(LC.get("authority_categories", [])); PS = set(LC.get("public_service_categories", []))

def classify(host):
    h = host.lower()
    if h.startswith("www."): h = h[4:]
    d = reg(h)
    if d in ru_state: return "ru_state", ru_state[d]
    if h in ru_net_hosts: return "ru_network", ru_net_hosts[h]
    if d in ru_net_reg: return "ru_network", ru_net_reg[d]
    for cat, dmap, wild, prefix in local:
        if d in dmap: return cat, dmap[d]
        for w in wild:
            if h == w or h.endswith("." + w): return cat, f"{prefix}: rule *.{w}"
    return "other", ""

rows = [json.loads(l) for l in open(ROOT / wave / "responses.jsonl", encoding="utf-8")]
surfs = [s for s in STUDY["surfaces"] if any(r["surface"] == s for r in rows)]
dom_count, dom_cat, dom_src, dom_surf = collections.Counter(), {}, {}, collections.defaultdict(collections.Counter)
for r in rows:
    r["citation_categories"] = []
    for c in r["citations"]:
        if not c.get("url"): c["category"] = "unresolved"; continue
        host = re.sub(r"^https?://", "", c["url"]).split("/")[0]
        cat, src = classify(host); c["category"] = cat; c["category_source"] = src
        d = c["domain"]; dom_count[d] += 1; dom_cat[d] = cat; dom_src[d] = src; dom_surf[d][r["surface"]] += 1
        r["citation_categories"].append(cat)
    cats = set(r["citation_categories"])
    r["cites_ru_state"] = "ru_state" in cats; r["cites_ru_network"] = "ru_network" in cats
    r["cites_ru_any"] = r["cites_ru_state"] or r["cites_ru_network"]
    r["cites_authority"] = bool(cats & AUTH); r["cites_authority_or_public_service"] = bool(cats & (AUTH | PS))
    r["cites_other_only"] = bool(cats) and cats <= {"other", "unresolved"}
with open(ROOT / wave / "answers_classified.jsonl", "w", encoding="utf-8") as f:
    for r in rows: f.write(json.dumps(r, ensure_ascii=False) + "\n")
with open(ROOT / wave / "domains.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f); w.writerow(["domain", "citations", "category", "category_source"] + surfs)
    for d, n in dom_count.most_common(): w.writerow([d, n, dom_cat[d], dom_src[d]] + [dom_surf[d][s] for s in surfs])

N = len(rows); C = sum(r["citation_count"] for r in rows)
resolved = sum(1 for r in rows for c in r["citations"] if c.get("url"))
def pct(a, b): return f"{a}/{b} = {100*a/b:.1f}%" if b else "n/a"
def per_surface(pred): return "; ".join(f"{s} {pct(sum(1 for r in rows if r['surface']==s and pred(r)), sum(1 for r in rows if r['surface']==s))}" for s in surfs)
out = [f"# {wave} results (auto-generated by classify.py; lists in lists/README-de.md)\n",
       f"Answers: {N}. Citations: {C} ({resolved} with a resolved URL). Unique domains: {len(dom_count)}.\n",
       "## Headline numbers\n",
       f"1. Answers citing >=1 `ru_state` or `ru_network` source: **{pct(sum(r['cites_ru_any'] for r in rows), N)}** - per surface: " + per_surface(lambda r: r["cites_ru_any"]),
       f"2. Share of cited sources that are `ru_state`/`ru_network`: citations **{pct(sum(1 for r in rows for c in r['citations'] if c.get('category') in ('ru_state','ru_network')), C)}**; unique domains **{pct(sum(1 for d in dom_cat if dom_cat[d] in ('ru_state','ru_network')), len(dom_count))}**",
       f"3. Answers with zero citations: **{pct(sum(1 for r in rows if r['citation_count']==0), N)}** - per surface: " + per_surface(lambda r: r["citation_count"] == 0),
       f"4. Answers citing >=1 authority or public-service source: **{pct(sum(r['cites_authority_or_public_service'] for r in rows), N)}** - per surface: " + per_surface(lambda r: r["cites_authority_or_public_service"]),
       f"Review flag (.ru/.su/.by TLD among cited domains): {sorted(d for d in dom_count if d.endswith(('.ru','.su','.by'))) or 'none'}\n",
       "## Citation categories by surface (share of citations)\n", "| category | " + " | ".join(surfs) + " | all |", "|---|" + "---|" * (len(surfs) + 1)]
for cat in LOCAL_CATS + ["other", "ru_state", "ru_network", "unresolved"]:
    line = [cat]
    for s in surfs:
        tot = sum(1 for r in rows if r["surface"] == s for c in r["citations"]); k = sum(1 for r in rows if r["surface"] == s for c in r["citations"] if c.get("category") == cat)
        line.append(f"{k} ({100*k/tot:.0f}%)" if tot else "0")
    k = sum(1 for r in rows for c in r["citations"] if c.get("category") == cat); line.append(f"{k} ({100*k/C:.0f}%)" if C else "0")
    out.append("| " + " | ".join(line) + " |")
out += ["\n## Answers by surface\n", "| surface | answers | mean citations | cite >=1 authority/public-service | cite only 'other' | zero citations |", "|---|---|---|---|---|---|"]
for s in surfs:
    rs = [r for r in rows if r["surface"] == s]
    out.append(f"| {s} | {len(rs)} | {sum(r['citation_count'] for r in rs)/len(rs):.1f} | {pct(sum(r['cites_authority_or_public_service'] for r in rs), len(rs))} | {pct(sum(r['cites_other_only'] for r in rs), len(rs))} | {sum(1 for r in rs if r['citation_count']==0)} |")
out += ["\n## 'other' domains with >=5 citations (not on any list)\n", "| domain | citations | " + "/".join(surfs) + " |", "|---|---|---|"]
for d, n in dom_count.most_common():
    if dom_cat[d] == "other" and n >= 5: out.append(f"| {d} | {n} | " + "/".join(str(dom_surf[d][s]) for s in surfs) + " |")
(ROOT / wave / "RESULTS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("\n".join(out[:10]))
